<?php
declare(strict_types=1);

namespace App\Services;

use App\Core\Database;
use App\Core\Logger;
use App\Repositories\AdminRepository;
use Throwable;

final class AdminManagementService
{
    public function __construct(
        private readonly AdminRepository    $admins = new AdminRepository(),
        private readonly NotificationService $notify = new NotificationService(),
        private readonly AuditService       $audit  = new AuditService(),
        private readonly TaskLockService    $locks  = new TaskLockService(),
    ) {}

    // ================================================================
    // CREATE
    // ================================================================

    /**
     * @return array{ok:bool,id?:int,password?:string,errors?:array<string,string>}
     */
    public function create(int $superAdminId, array $input): array
    {
        $data = [
            'full_name'            => trim((string) ($input['full_name'] ?? '')),
            'email'                => strtolower(trim((string) ($input['email'] ?? ''))),
            'username'             => strtolower(trim((string) ($input['username'] ?? ''))),
            'phone'                => trim((string) ($input['phone'] ?? '')),
            'password'             => (string) ($input['password'] ?? ''),
            'confirm_password'     => (string) ($input['confirm_password'] ?? ''),
            'status'               => (string) ($input['status'] ?? 'active'),
            'max_concurrent_tasks' => (int) ($input['max_concurrent_tasks'] ?? 0),
            'must_change_password' => !empty($input['must_change_password']),
        ];

        $errors = $this->validateCommon($data, null);
        if ($errors) return ['ok' => false, 'errors' => $errors];

        // Auto-generate a strong password if none provided
        $autoGenerated = false;
        if ($data['password'] === '') {
            $data['password'] = $this->generateStrongPassword();
            $autoGenerated = true;
        }
        if (strlen($data['password']) < 8) {
            return ['ok' => false, 'errors' => ['password' => 'Password must be at least 8 characters.']];
        }
        if ($data['password'] !== $data['confirm_password'] && !$autoGenerated) {
            return ['ok' => false, 'errors' => ['confirm_password' => 'Passwords do not match.']];
        }

        try {
            $id = $this->admins->create([
                'full_name'            => $data['full_name'],
                'email'                => $data['email'],
                'username'             => $data['username'],
                'phone'                => $data['phone'],
                'password_hash'        => password_hash($data['password'], PASSWORD_DEFAULT),
                'status'               => $data['status'],
                'max_concurrent_tasks' => $data['max_concurrent_tasks'],
                'must_change_password' => $autoGenerated || $data['must_change_password'],
                'created_by'           => $superAdminId,
            ]);

            $this->audit->log(
                'ADMIN_CREATED', 'admin', $id,
                'Admin account created: ' . $data['email'],
                newValues: [
                    'full_name' => $data['full_name'],
                    'email'     => $data['email'],
                    'username'  => $data['username'],
                    'status'    => $data['status'],
                ],
                userType: 'super_admin', userId: $superAdminId
            );

            $this->notify->notifyAdmin(
                $id,
                'Welcome to the team',
                'Your admin account has been created. '
                    . ($autoGenerated || $data['must_change_password']
                        ? 'You will be required to change your password at first login.'
                        : 'You can sign in now.'),
                'system',
                '/admin/profile'
            );

            return [
                'ok'       => true,
                'id'       => $id,
                'password' => $autoGenerated ? $data['password'] : null,
            ];
        } catch (Throwable $e) {
            Logger::error('Admin create failed', ['error' => $e->getMessage()]);
            return ['ok' => false, 'errors' => ['general' => 'Could not create the admin account.']];
        }
    }

    // ================================================================
    // UPDATE (profile fields only)
    // ================================================================

    public function update(int $superAdminId, int $adminId, array $input): array
    {
        $existing = $this->admins->findById($adminId);
        if (!$existing) return ['ok' => false, 'errors' => ['general' => 'Admin not found.']];

        $data = [
            'full_name'            => trim((string) ($input['full_name'] ?? '')),
            'phone'                => trim((string) ($input['phone'] ?? '')),
            'max_concurrent_tasks' => (int) ($input['max_concurrent_tasks'] ?? 0),
        ];
        $errors = $this->validateCommon($data, $adminId, false);
        if ($errors) return ['ok' => false, 'errors' => $errors];

        $this->admins->update($adminId, $data);

        $old = [];
        $new = [];
        foreach ($data as $k => $v) {
            if ((string) ($existing[$k] ?? '') !== (string) $v) {
                $old[$k] = $existing[$k] ?? null;
                $new[$k] = $v;
            }
        }
        if ($old) {
            $this->audit->log(
                'ADMIN_UPDATED', 'admin', $adminId,
                'Admin account updated: ' . $existing['email'],
                oldValues: $old, newValues: $new,
                userType: 'super_admin', userId: $superAdminId
            );
        }
        return ['ok' => true];
    }

    // ================================================================
    // STATUS (activate / deactivate / suspend)
    // ================================================================

    public function setStatus(int $superAdminId, int $adminId, string $status): array
    {
        if (!in_array($status, ['active', 'inactive', 'suspended'], true)) {
            return ['ok' => false, 'errors' => ['general' => 'Invalid status.']];
        }
        $existing = $this->admins->findById($adminId);
        if (!$existing) return ['ok' => false, 'errors' => ['general' => 'Admin not found.']];
        if ($existing['status'] === $status) return ['ok' => true];

        $released = 0;
        if ($status !== 'active') {
            // Release any tasks the admin currently holds. This must not fail
            // even if the release partially succeeds; we log the count and move on.
            $released = $this->locks->releaseAllForAdmin(
                $adminId,
                'Admin deactivated by Super Admin'
            );
        }

        $this->admins->setStatus($adminId, $status);

        $this->audit->log(
            'ADMIN_STATUS_CHANGED', 'admin', $adminId,
            'Admin status changed to ' . $status . ($released ? " ($released tasks released)" : ''),
            oldValues: ['status' => $existing['status']],
            newValues: ['status' => $status, 'tasks_released' => $released],
            userType: 'super_admin', userId: $superAdminId
        );

        if ($status === 'active') {
            $this->notify->notifyAdmin(
                $adminId,
                'Account reactivated',
                'Your admin account has been reactivated. Welcome back.',
                'system',
                '/admin/dashboard'
            );
        } else {
            $this->notify->notifyAdmin(
                $adminId,
                'Account ' . $status,
                'Your admin account has been ' . $status . '.'
                    . ($released ? ' ' . $released . ' task(s) were returned to the pool.' : ''),
                'system'
            );
        }

        return ['ok' => true, 'released' => $released];
    }

    // ================================================================
    // PASSWORD RESET
    // ================================================================

    /**
     * Super Admin sets a new password on the admin's behalf. The admin will be
     * forced to change it at next login unless $forceChange is false.
     *
     * @return array{ok:bool,password?:string,errors?:array<string,string>}
     */
    public function resetPassword(int $superAdminId, int $adminId, ?string $newPassword = null, bool $forceChange = true): array
    {
        $existing = $this->admins->findById($adminId);
        if (!$existing) return ['ok' => false, 'errors' => ['general' => 'Admin not found.']];

        $autoGenerated = false;
        if ($newPassword === null || $newPassword === '') {
            $newPassword   = $this->generateStrongPassword();
            $autoGenerated = true;
        }
        if (strlen($newPassword) < 8) {
            return ['ok' => false, 'errors' => ['password' => 'Password must be at least 8 characters.']];
        }

        $this->admins->updatePassword($adminId, password_hash($newPassword, PASSWORD_DEFAULT));
        $this->admins->setMustChangePassword($adminId, $forceChange);
        $this->admins->setRememberToken($adminId, null);

        $this->audit->log(
            'ADMIN_PASSWORD_RESET', 'admin', $adminId,
            'Password reset by Super Admin',
            newValues: ['force_change' => $forceChange, 'generated' => $autoGenerated],
            userType: 'super_admin', userId: $superAdminId
        );

        $this->notify->notifyAdmin(
            $adminId,
            'Password reset',
            'Your password was reset by an administrator. '
                . ($forceChange ? 'You must change it at next login.' : ''),
            'system'
        );

        return [
            'ok'       => true,
            'password' => $autoGenerated ? $newPassword : null,
        ];
    }

    public function forcePasswordChange(int $superAdminId, int $adminId): array
    {
        $existing = $this->admins->findById($adminId);
        if (!$existing) return ['ok' => false, 'errors' => ['general' => 'Admin not found.']];

        $this->admins->setMustChangePassword($adminId, true);

        $this->audit->log(
            'ADMIN_FORCE_PASSWORD_CHANGE', 'admin', $adminId,
            'Forced password change at next login',
            userType: 'super_admin', userId: $superAdminId
        );
        return ['ok' => true];
    }

    // ================================================================
    // DELETE — never hard-deletes financial history
    // ================================================================

    /**
     * @return array{ok:bool,soft?:bool,errors?:array<string,string>}
     */
    public function delete(int $superAdminId, int $adminId): array
    {
        $existing = $this->admins->findById($adminId);
        if (!$existing) return ['ok' => false, 'errors' => ['general' => 'Admin not found.']];

        // Never hard-delete an admin with any financial history or any task history.
        if ($this->admins->hasAnyWithdrawals($adminId)
            || $this->admins->hasAnySubmissions($adminId)) {
            $result = $this->setStatus($superAdminId, $adminId, 'inactive');
            if (!$result['ok']) return $result;
            return ['ok' => true, 'soft' => true];
        }

        try {
            // Release any still-held tasks first (shouldn't be any, but be safe)
            $this->locks->releaseAllForAdmin($adminId, 'Admin deleted');

            Database::execute('DELETE FROM admins WHERE id = :id', [':id' => $adminId]);

            $this->audit->log(
                'ADMIN_DELETED', 'admin', $adminId,
                'Admin account deleted: ' . $existing['email'],
                oldValues: $existing,
                userType: 'super_admin', userId: $superAdminId
            );
            return ['ok' => true];
        } catch (Throwable $e) {
            Logger::error('Admin delete failed', ['error' => $e->getMessage(), 'id' => $adminId]);
            return ['ok' => false, 'errors' => ['general' => 'Could not delete the admin.']];
        }
    }

    // ================================================================
    // HELPERS
    // ================================================================

    private function validateCommon(array $data, ?int $exceptId, bool $requireIdentity = true): array
    {
        $errors = [];

        if ($requireIdentity) {
            if (empty($data['full_name']) || mb_strlen($data['full_name']) < 3) {
                $errors['full_name'] = 'Full name is required (min 3 characters).';
            }
            if (empty($data['email']) || !filter_var($data['email'], FILTER_VALIDATE_EMAIL)) {
                $errors['email'] = 'A valid email address is required.';
            } elseif ($this->admins->emailExists($data['email'], $exceptId)) {
                $errors['email'] = 'This email is already in use.';
            }
            if (empty($data['username']) || !preg_match('/^[a-z0-9_\.]{3,60}$/', $data['username'])) {
                $errors['username'] = 'Username must be 3–60 chars using a–z, 0–9, dot or underscore.';
            } elseif ($this->admins->usernameExists($data['username'], $exceptId)) {
                $errors['username'] = 'This username is already in use.';
            }
        } else {
            if (empty($data['full_name']) || mb_strlen($data['full_name']) < 3) {
                $errors['full_name'] = 'Full name is required (min 3 characters).';
            }
        }

        if (empty($data['phone']) || !preg_match('/^[0-9+\-\s()]{7,20}$/', (string) $data['phone'])) {
            $errors['phone'] = 'A valid phone number is required.';
        }

        if (isset($data['status']) && !in_array($data['status'], ['active','inactive','suspended'], true)) {
            $errors['status'] = 'Invalid status.';
        }
        if (isset($data['max_concurrent_tasks']) && (int) $data['max_concurrent_tasks'] < 0) {
            $errors['max_concurrent_tasks'] = 'Max concurrent tasks cannot be negative.';
        }

        return $errors;
    }

    private function generateStrongPassword(int $length = 14): string
    {
        // Guarantee at least one of each category
        $lower  = 'abcdefghijkmnopqrstuvwxyz';
        $upper  = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
        $digits = '23456789';
        $symbol = '!@#$%&*?-_';
        $all    = $lower . $upper . $digits . $symbol;

        $password = $lower[random_int(0, strlen($lower) - 1)]
                  . $upper[random_int(0, strlen($upper) - 1)]
                  . $digits[random_int(0, strlen($digits) - 1)]
                  . $symbol[random_int(0, strlen($symbol) - 1)];

        for ($i = 4; $i < $length; $i++) {
            $password .= $all[random_int(0, strlen($all) - 1)];
        }
        // Fisher-Yates shuffle
        $arr = str_split($password);
        for ($i = count($arr) - 1; $i > 0; $i--) {
            $j = random_int(0, $i);
            [$arr[$i], $arr[$j]] = [$arr[$j], $arr[$i]];
        }
        return implode('', $arr);
    }
}